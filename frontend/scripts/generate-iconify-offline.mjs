import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { getIcons } from '@iconify/utils';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceRoot = path.join(projectRoot, 'src');
const iconSetRoot = path.join(projectRoot, 'node_modules', '@iconify', 'json', 'json');
const outputFile = path.join(sourceRoot, 'assets', 'generated', 'iconify-offline.ts');
const sourceExtensions = new Set(['.json', '.ts', '.tsx', '.vue']);
const iconPattern = /\b([a-z0-9]+(?:-[a-z0-9]+)*):([a-z0-9]+(?:-[a-z0-9]+)*)\b/g;

// These names are supplied by the phase-one backend route metadata, so they
// cannot be discovered by scanning the frontend source tree alone.
const runtimeIcons = [
  'lucide:book-open-check',
  'lucide:brain',
  'lucide:bug-play',
  'lucide:blocks',
  'lucide:bot',
  'lucide:calculator',
  'lucide:chart-no-axes-combined',
  'lucide:chart-spline',
  'lucide:database',
  'lucide:folders',
  'lucide:house',
  'lucide:library',
  'lucide:list-checks',
  'lucide:message-square',
  'lucide:layout-dashboard',
  'lucide:package-check',
  'lucide:pen-line',
  'lucide:scan-search',
  'lucide:settings',
  'lucide:shield-check',
  'lucide:user-round',
  'lucide:waypoints',
  'lucide:workflow'
];

async function listSourceFiles(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const absolutePath = path.join(directory, entry.name);

    if (entry.isDirectory()) {
      files.push(...(await listSourceFiles(absolutePath)));
    } else if (sourceExtensions.has(path.extname(entry.name))) {
      files.push(absolutePath);
    }
  }

  return files;
}

function addIcon(iconNames, value) {
  const separator = value.indexOf(':');
  const prefix = value.slice(0, separator);
  const name = value.slice(separator + 1);

  if (!prefix || !name) return;

  const names = iconNames.get(prefix) || new Set();
  names.add(name);
  iconNames.set(prefix, names);
}

async function iconSetExists(prefix) {
  try {
    await fs.access(path.join(iconSetRoot, `${prefix}.json`));
    return true;
  } catch {
    return false;
  }
}

async function collectIconNames() {
  const candidates = new Map();

  for (const file of await listSourceFiles(sourceRoot)) {
    const source = await fs.readFile(file, 'utf8');

    for (const match of source.matchAll(iconPattern)) {
      addIcon(candidates, `${match[1]}:${match[2]}`);
    }
  }

  for (const icon of runtimeIcons) addIcon(candidates, icon);

  const result = new Map();

  for (const [prefix, names] of candidates) {
    if (await iconSetExists(prefix)) result.set(prefix, names);
  }

  return result;
}

async function buildCollections(iconNames) {
  const collections = [];

  for (const prefix of [...iconNames.keys()].sort()) {
    const requested = [...iconNames.get(prefix)].sort();
    const source = JSON.parse(await fs.readFile(path.join(iconSetRoot, `${prefix}.json`), 'utf8'));
    const subset = getIcons(source, requested, true);
    const missing = subset ? subset.not_found || [] : requested;

    if (!subset || missing.length > 0) {
      throw new Error(`Missing Iconify icons in ${prefix}: ${missing.join(', ')}`);
    }

    delete subset.info;
    collections.push(subset);
  }

  return collections;
}

const iconNames = await collectIconNames();
const collections = await buildCollections(iconNames);
const iconCount = collections.reduce(
  (count, collection) => count + Object.keys(collection.icons || {}).length + Object.keys(collection.aliases || {}).length,
  0
);
const generated = `// Generated by scripts/generate-iconify-offline.mjs. Do not edit manually.\n\nimport type { IconifyJSON } from '@iconify/vue/offline';\n\nexport const offlineIconCollections: IconifyJSON[] = ${JSON.stringify(collections, null, 2)};\n`;

await fs.mkdir(path.dirname(outputFile), { recursive: true });
await fs.writeFile(outputFile, generated);
console.log(`Generated ${iconCount} offline icons in ${collections.length} collections.`);
